package dev.kubejseditor.script;

import com.google.gson.*;
import dev.kubejseditor.model.EditorProject;
import dev.kubejseditor.model.ItemKinds;
import dev.kubejseditor.recipe.RecipeAdapters;
import dev.kubejseditor.recipe.CraftingGrid;
import dev.kubejseditor.storage.ProjectStore;
import java.nio.charset.StandardCharsets;
import java.util.*;

public final class KjsGenerator {
    private static final String HEADER = "// Generated by KubeJS Editor. Edit through the editor or keep hand-written code elsewhere.\n";
    public record Output(Map<String, byte[]> files, boolean restartRequired, boolean resourcesChanged) {}
    public static String quote(String value) { return ProjectStore.JSON.toJson(value); }
    private static byte[] bytes(String value) { return value.getBytes(StandardCharsets.UTF_8); }
    public static Output generate(EditorProject project) {
        project.validateStructure(); Map<String, byte[]> files = new LinkedHashMap<>();
        StringBuilder recipe = new StringBuilder(HEADER + "// priority: -100\nServerEvents.recipes(event => {\n");
        // In KubeJS 2101.7.2 an IDFilter only searches originalRecipes. Remove matching
        // additions from earlier script callbacks explicitly, before introducing our versions.
        List<String> ids=project.recipes.values().stream().filter(d->d.enabled).map(d->d.id).toList();
        if(!ids.isEmpty())recipe.append("  const editorIds = ").append(ProjectStore.JSON.toJson(ids)).append(";\n  event.addedRecipes.forEach(recipe => { if (editorIds.indexOf(String(recipe.getId())) >= 0) recipe.remove(); });\n");
        // Explicit removals first, additions last. Each ID is emitted exactly once.
        for (var d : project.recipes.values()) if (d.enabled && Set.of("remove","replace").contains(d.operation)) recipe.append("  event.remove({id:").append(quote(d.id)).append("});\n");
        for (var d : project.recipes.values()) if (d.enabled && !d.operation.equals("remove")) {
            dev.kubejseditor.recipe.SimpleRecipes.restore(d);
            JsonObject generated=CraftingGrid.generated(d);
            List<String> errors = RecipeAdapters.validateData(generated);
            if (!errors.isEmpty()) throw new IllegalArgumentException(d.id + "：" + String.join("；", errors));
            recipe.append("  event.custom(").append(ProjectStore.JSON.toJson(generated)).append(").id(").append(quote(d.id)).append(");\n");
        }
        recipe.append("});\n"); if(!project.recipes.isEmpty())files.put("kubejs/server_scripts/kubejs_editor/recipes.js", bytes(recipe.toString()));
        StringBuilder startup = new StringBuilder(HEADER), tips = new StringBuilder(HEADER);
        JsonObject lang = new JsonObject();
        boolean restart = !project.items.isEmpty(), resources = false;
        for (var item : project.items.values()) {
            validateItem(item);
            String id = quote(item.id);
            String kind=ItemKinds.kind(item);var attributes=ItemKinds.attributes(item);
            if (item.register) {
                if(kind.equals("block")){
                    BlockRegistration.append(startup,item);
                    if(dev.kubejseditor.model.BlockKinds.options(item).type.equals("door")){files.put(BlockRegistration.itemModelPath(item),BlockRegistration.itemModel(item));resources=true;}
                }else{
                    startup.append("StartupEvents.registry('item', event => {\n  event.create(").append(id);if(!kind.equals("basic")&&!kind.equals("food"))startup.append(',').append(quote(kind));startup.append(')');
                    for(var prop:item.properties.entrySet())if(Set.of("maxStackSize","maxDamage","burnTime").contains(prop.getKey()))startup.append('.').append(prop.getKey()).append('(').append(prop.getValue()).append(')');
                    if(ItemKinds.tool(kind)){if(item.properties.has("maxDamage"))startup.append(".modifyTier(tier => tier.setUses(").append(item.properties.get("maxDamage")).append("))");startup.append(".attackDamageBonus(0).attackDamageBaseline(").append(ItemKinds.value(item,"damage",6)-1).append(").speedBaseline(").append(ItemKinds.value(item,"attackSpeed",1.6)-4).append(").speed(").append(ItemKinds.value(item,"miningSpeed",6)).append(')');}
                    startup.append(".texture(").append(quote(item.texture)).append(")");
                    if(item.food||kind.equals("food"))startup.append(".food(food => food.nutrition(").append(number(item.properties,"nutrition",4)).append(").saturation(").append(number(item.properties,"saturation",.3)).append("))");startup.append(";\n});\n");
                }
            }
            if ((!item.register && (!item.properties.isEmpty() || item.food)) || !attributes.isEmpty() || item.replaceAttributes) {
                startup.append("ItemEvents.modification(event => {\n  event.modify(").append(id).append(", item => {\n");
                if (!item.register) {
                    for (var prop : item.properties.entrySet()) {
                        if (Set.of("maxStackSize","maxDamage","burnTime").contains(prop.getKey())) startup.append("    item.").append(prop.getKey()).append(" = ").append(prop.getValue()).append(";\n");
                    }
                    if (item.food) startup.append("    item.setFood(").append(number(item.properties,"nutrition",4)).append(',').append(number(item.properties,"saturation",0.3)).append(");\n");
                }
                if (!attributes.isEmpty() || item.replaceAttributes) {
                    JsonArray modifiers = new JsonArray();
                    for (var a : attributes) {
                        JsonObject modifier = new JsonObject(); modifier.addProperty("id", a.id); modifier.addProperty("amount", a.amount); modifier.addProperty("operation", a.operation);
                        JsonObject entry = new JsonObject(); entry.addProperty("attribute", a.attribute); entry.add("modifier", modifier); entry.addProperty("slot", a.slot); modifiers.add(entry);
                    }
                    startup.append("    item.setAttributeModifiers(").append(ProjectStore.JSON.toJson(modifiers)).append(");\n");
                }
                startup.append("  });\n});\n");
            }
            String ownedItem=dev.kubejseditor.model.RegistrationMembers.itemId(item);
            if(dev.kubejseditor.model.RegistrationMembers.crop(item)){lang.addProperty("item."+ownedItem.replace(':','.'),item.block.crop.seedName);resources=true;}
            if (!item.tooltip.isEmpty()) tips.append("ItemEvents.modifyTooltips(event => { event.add(").append(quote(ownedItem)).append(',').append(ProjectStore.JSON.toJson(item.tooltip)).append("); });\n");
            if (item.name != null && !item.name.isBlank()) { lang.addProperty(item.nameKey!=null&&!item.nameKey.isBlank()?item.nameKey:(kind.equals("block")?"block.":"item.") + item.id.replace(':','.'), item.name); resources = true; }
        }
        if(startup.length()>HEADER.length())files.put("kubejs/startup_scripts/kubejs_editor/items.js", bytes(startup.toString()));
        if(tips.length()>HEADER.length())files.put("kubejs/client_scripts/kubejs_editor/tooltips.js", bytes(tips.toString()));
        if(!lang.isEmpty()){
            files.put("kubejs/assets/kubejs_editor/lang/zh_cn.json", bytes(ProjectStore.JSON.toJson(lang)));
            files.put("kubejs/assets/kubejs_editor/lang/en_us.json", bytes(ProjectStore.JSON.toJson(lang)));
        }
        files.put(ProjectStore.FILE, bytes(ProjectStore.JSON.toJson(project)));
        if(!project.items.isEmpty())files.put("kubejs/config/kubejs_editor/applied-items.json",bytes(ProjectStore.JSON.toJson(project.items.values().stream().filter(i->i.register).flatMap(i->dev.kubejseditor.model.RegistrationMembers.of(i).stream()).map(m->m.id()).distinct().toList())));
        return new Output(files, restart, resources);
    }
    public static void validateItem(EditorProject.ItemDraft item) {
        EditorProject.requireId(item.id);
        ItemKinds.validate(item);var attributes=ItemKinds.attributes(item);
        for (var e : item.properties.entrySet()) {
            if (!Set.of("maxStackSize","maxDamage","burnTime","nutrition","saturation").contains(e.getKey())) throw new IllegalArgumentException("不支持的物品属性：" + e.getKey());
            double n = e.getValue().getAsDouble(); if (!Double.isFinite(n) || n < 0) throw new IllegalArgumentException("物品属性必须是非负数");
            if (!e.getKey().equals("saturation") && n != Math.rint(n)) throw new IllegalArgumentException("该物品属性必须是整数");
        }
        double stack = number(item.properties,"maxStackSize",1), damage = number(item.properties,"maxDamage",0);
        if (stack < 1 || stack > 99) throw new IllegalArgumentException("堆叠数量应在 1～99 之间");
        if (stack > 1 && damage > 0) throw new IllegalArgumentException("有耐久的物品不能堆叠");
        if (item.register) EditorProject.requireId(item.texture);
        Set<String> identifiers = new HashSet<>();
        for (var a : attributes) {
            EditorProject.requireId(a.attribute); EditorProject.requireId(a.id);
            if (!identifiers.add(a.id)) throw new IllegalArgumentException("属性修饰符 ID 重复");
            if (!Double.isFinite(a.amount)) throw new IllegalArgumentException("属性数值无效");
            if (!Set.of("add_value","add_multiplied_base","add_multiplied_total").contains(a.operation)) throw new IllegalArgumentException("无效属性运算");
            if (!Set.of("any","mainhand","offhand","hand","head","chest","legs","feet","armor","body").contains(a.slot)) throw new IllegalArgumentException("无效装备槽");
        }
    }
    private static double number(JsonObject o, String key, double fallback) { return o.has(key) ? o.get(key).getAsDouble() : fallback; }
}
